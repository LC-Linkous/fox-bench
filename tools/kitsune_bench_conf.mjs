#!/usr/bin/env node
// kitsune_bench_conf.mjs — the bench "conference": one current_conf.h per kitsune project, written by the page's own
// header exporter (js/model/vendor/kitsune.js) from the templates' defaults, with plainly-labelled fox-bench names.
// SPDX-License-Identifier: GPL-2.0-only
//
//   node tools/kitsune_bench_conf.mjs            → firmware/kitsune/bench/<project>.h (committed; re-run after a change)
//   node tools/kitsune_bench_conf.mjs --check    → exit 1 when the committed files differ (CI)
//
// tools/build_kitsune.py --conf-dir firmware/kitsune/bench installs these as src/current_conf.h in a kitsune checkout
// before building, so an image fox-bench builds never carries whichever event's configuration kitsune's tree had
// checked out. kitsune's header is one file per project with every tier/mode section the envs select by build flag;
// a fox-bench export is one fox, so each file here is the concatenation of one export per section the project's
// envs need. The values are bench values — nothing here is any event's configuration.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { exportHeader, TEMPLATES } from '../js/model/vendor/kitsune.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const defaults = (template, board) => JSON.parse(readFileSync(join(ROOT, 'firmware/templates', template, 'defaults', board + '.json'), 'utf8'));
// documented, locally administered, obviously-bench MACs (F2 = kitsune's own first byte)
const macs = { easyAp: 'F2:B0:00:00:00:01', hardAp: 'F2:B0:00:00:00:02', fiveEasy: 'F2:B0:00:00:00:03', fiveHard: 'F2:B0:00:00:00:04', easyCl: 'F2:B0:00:00:00:05', hardCl: 'F2:B0:00:00:00:06', ble: 'F2:B0:00:00:00:07', bt: 'F2:B0:00:00:00:08', zb: 'F2:B0:00:00:00:00:00:09' };
const fox = (template, board, tier, patch) => {
  const cfg = defaults(template, board);
  cfg.challenge = { ...cfg.challenge, tier, name: `FOXBENCH ${template} ${tier}`, keyphrase: `Are you the FOXBENCH ${template} ${tier} fox?` };
  for (const [k, v] of Object.entries(patch || {})) cfg[k] = { ...cfg[k], ...v };
  return exportHeader(cfg);
};
const banner = p => `// fox-bench bench conference for kitsune's ${p} — generated by tools/kitsune_bench_conf.mjs, do not edit.\n// Bench values only: SSIDs/names say FOXBENCH, MACs are F2:B0:00:00:00:xx. Not any event's configuration.\n`;
const files = {
  'wifi_ap_client.h': banner('wifi/wifi_ap_client')
    + fox('wifi-ap', 'm5stack_atom_lite-kitsune', 'easy', { wifi: { ssid: 'FOXBENCH WiFi AP Easy', mac: macs.easyAp } })
    + fox('wifi-ap', 'm5stack_atom_lite-kitsune', 'hard', { wifi: { ssid: 'FOXBENCH WiFi AP Hard', mac: macs.hardAp, channel: 6, hidden: true } })
    + fox('wifi-ap', 'seeed_xiao_esp32c5-kitsune', 'easy', { wifi: { ssid: 'FOXBENCH WiFi 5GHz AP Easy', mac: macs.fiveEasy, band: '5', channel: 36 } })
    + fox('wifi-ap', 'seeed_xiao_esp32c5-kitsune', 'hard', { wifi: { ssid: 'FOXBENCH WiFi 5GHz AP Hard', mac: macs.fiveHard, band: '5', channel: 149, hidden: true } })
    + fox('wifi-client', 'm5stack_atom_lite-kitsune', 'easy', { wifi: { ssid: 'FOXBENCH WiFi Client Easy', mac: macs.easyCl } })
    + fox('wifi-client', 'm5stack_atom_lite-kitsune', 'hard', { wifi: { ssid: 'FOXBENCH WiFi Client Hard', mac: macs.hardCl } }),
  'iBeacon.h': banner('bluetooth/iBeacon')
    + fox('ble-ibeacon', 'm5stack_atom_lite-kitsune', 'easy', { ble: { device_name: 'FOXBENCH iBeacon Easy', mac: macs.ble } })
    + fox('ble-ibeacon', 'm5stack_atom_lite-kitsune', 'hard', { ble: { device_name: 'FOXBENCH iBeacon Hard', mac: macs.ble } }),
  'classic_discoverable.h': banner('bluetooth/classic_discoverable')
    + fox('bt-classic', 'm5stack_atom_lite-kitsune', 'easy', { bt: { name: 'FOXBENCH BT Classic Easy', mac: macs.bt } })
    + fox('bt-classic', 'm5stack_atom_lite-kitsune', 'hard', { bt: { name: 'FOXBENCH BT Classic Hard', mac: macs.bt } }),
  'zigbee_coordinator.h': banner('zigbee/zigbee_coordinator')
    + fox('zigbee-coordinator', 'seeed_xiao_esp32c5-kitsune', 'easy', { zigbee: { mac: macs.zb, channel: 15 } })
    + fox('zigbee-coordinator', 'seeed_xiao_esp32c5-kitsune', 'hard', { zigbee: { mac: macs.zb, channel: 25 } }),
};
const dir = join(ROOT, 'firmware/kitsune/bench'); mkdirSync(dir, { recursive: true });
let stale = 0;
for (const [name, text] of Object.entries(files)) {
  const p = join(dir, name);
  if (process.argv.includes('--check')) { if (!existsSync(p) || readFileSync(p, 'utf8') !== text) { console.log(`stale: firmware/kitsune/bench/${name} — run node tools/kitsune_bench_conf.mjs`); stale++; } }
  else { writeFileSync(p, text); console.log(`wrote firmware/kitsune/bench/${name} (${text.split('\n').length} lines)`); }
}
if (stale) process.exit(1);
if (process.argv.includes('--check')) console.log('kitsune bench conference headers are current');

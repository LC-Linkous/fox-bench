#!/usr/bin/env python3
"""check_docs.py — every repository path named in the Markdown files exists.

    python3 tools/check_docs.py

Looks in README.md, DESIGN.md, CONFIG.md, PROTOCOL.md, LICENSES.md, docs/*.md, tests/README.md and
firmware/*/README.md for tokens that look like repository paths (a directory prefix the repo has, or a
file extension the repo uses) and checks each against the tree. Documents drift away from code quietly;
this is the check that says `fs-drive.js` is a file this repository does not have.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = ["README.md", "DESIGN.md", "CONFIG.md", "PROTOCOL.md", "LICENSES.md", "tests/README.md", "firmware/foxlib-c/README.md"]
DOCS += sorted(os.path.join("docs", f) for f in os.listdir(os.path.join(ROOT, "docs")) if f.endswith(".md") and not (f.startswith("project-audit") or f.endswith("-plan.md")))   # audits and plans name files they propose
TOP = {"js", "css", "flasher", "boards", "hardware", "modules", "songs", "firmware", "tools", "tests", "docs", ".github", "foxlib", "core", "picofox", "templates", "sim"}
EXTS = (".js", ".mjs", ".py", ".c", ".h", ".json", ".md", ".yml", ".html", ".css", ".txt")
# names that are examples, generated, on a board, or otherwise not repository files
IGNORE = re.compile(r"^(fox|defaults|board|settings|INFO_UF2|INDEX|README|code|boot|audio|images|flash_log|foxbench-picofox|version|index|scenarios|template|project|CMakeLists|Makefile|fox-bench-diagnostics|package|package-lock|\.callsign|\.settings_crc|_site|build|node_modules|host_sim|json|cfg|melody|synth|schedule|sstv|morse|events|player|console|fs|main|flash_disk|msc_disk|si5351|usb_descriptors|tusb_config|picofox|fox-hunt-web|ff|ffconf|diskio)(\.[a-z0-9_]+)?$")
# generated by CI / a build, named on purpose
GENERATED = {"firmware/foxlib-c/picofox/foxbench-picofox.uf2", "firmware/foxlib-c/picofox/foxbench-picofox.json", "firmware/foxlib-c/tests/build/host_sim"}

tracked = set(subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split())
dirs = {""}
for t in tracked:
    p = t
    while "/" in p: p = p.rsplit("/", 1)[0]; dirs.add(p)

def exists(path, doc=""):
    """The path as written, or relative to the document's directory, or under firmware/ (docs say `foxlib/cfg.py`)."""
    path = path.rstrip("/")
    cands = [path, os.path.normpath(os.path.join(os.path.dirname(doc), path)), "firmware/" + path, "firmware/foxlib-c/" + path]
    return any(c in tracked or c in dirs or c in GENERATED or os.path.exists(os.path.join(ROOT, c)) for c in cands)

token = re.compile(r"`([A-Za-z0-9_./-]+)`")
problems = []
for doc in DOCS:
    text = open(os.path.join(ROOT, doc), encoding="utf-8").read()
    for m in token.finditer(text):
        tok = m.group(1).rstrip(".")
        if not tok or tok.startswith("-") or "<" in tok: continue
        looks_like_path = ("/" in tok and tok.split("/")[0] in TOP) or (tok.endswith(EXTS) and "/" in tok)
        if not looks_like_path: continue
        if any(seg.startswith("<") or seg in ("…", "...") for seg in tok.split("/")): continue
        if "*" in tok or "<" in tok: continue
        base = tok.rsplit("/", 1)[-1]
        if IGNORE.match(base) and not tok.startswith(("js/", "tools/", "firmware/sim/", "firmware/foxlib/", "firmware/foxlib-c/core/", "firmware/foxlib-c/picofox/", "tests/", ".github/")): continue
        if not exists(tok, doc): problems.append(f"{doc}: `{tok}` is not in the repository")

if problems:
    print(f"docs: {len(problems)} path(s) named that do not exist")
    for p in sorted(set(problems)): print("  " + p)
    sys.exit(1)
print(f"docs ok: paths in {len(DOCS)} documents exist")
